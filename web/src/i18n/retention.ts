function createRetentionTranslation(phrases: RetentionPhrases) {
  return {
    title: phrases.title,
    description: phrases.description,
    loadFailed: phrases.failed,
    ruleRequired: phrases.ruleRequired,
    previewFailed: phrases.failed,
    saveFailed: phrases.failed,
    saved: phrases.saved,
    noChanges: phrases.noChanges,
    triggerFailed: phrases.failed,
    triggerQueued: phrases.queued,
    saveBeforeTrigger: phrases.saveBefore,
    notRun: phrases.notRun,
    unsaved: phrases.unsaved,
    reload: phrases.reload,
    preview: phrases.preview,
    save: phrases.save,
    enabled: phrases.enabled,
    enabledHint: phrases.description,
    daysRule: phrases.days,
    daysRuleHint: phrases.description,
    daysInput: phrases.days,
    daysInvalid: phrases.invalid,
    daysUnit: phrases.days,
    capacityRule: phrases.capacity,
    capacityRuleHint: phrases.description,
    capacityInput: phrases.capacity,
    capacityInvalid: phrases.invalid,
    storageWarningTitle: phrases.storageWarningTitle,
    storageWarningDescription: phrases.storageWarningDescription,
    statusTitle: phrases.status,
    running: phrases.running,
    overLimit: phrases.overLimit,
    idle: phrases.idle,
    usage: phrases.usage,
    managedDays: phrases.days,
    lastCleanup: phrases.status,
    lastResult: phrases.status,
    deletedSummary: phrases.deleted,
    capacityProgress: phrases.capacity,
    lastScan: phrases.status,
    triggerSource: phrases.status,
    blocked: phrases.waiting,
    lastError: phrases.error,
    trigger: phrases.run,
    previewTitle: phrases.preview,
    previewSummary: phrases.deleted,
    overLimitAfterPreview: phrases.overLimit,
    previewEmpty: phrases.empty,
    skipped: phrases.skipped,
    saveConfirmTitle: phrases.confirm,
    saveConfirm: phrases.save,
    cancel: phrases.cancel,
    saveConfirmDescription: phrases.danger,
    saveConfirmSummary: phrases.deleted,
    triggerConfirmTitle: phrases.confirm,
    triggerConfirm: phrases.run,
    triggerConfirmDescription: phrases.danger,
    discardTitle: phrases.discard,
    discardConfirm: `${phrases.discard} · ${phrases.reload}`,
    discardDescription: phrases.discard,
    conflictTitle: phrases.changed,
    conflictReload: phrases.reload,
    conflictKeepEditing: phrases.keepEditing,
    conflictDescription: phrases.changed
  };
}

function createLocale(phrases: RetentionPhrases, recordingCleaned: string) {
  return { retention: createRetentionTranslation(phrases), recordingCleaned };
}

