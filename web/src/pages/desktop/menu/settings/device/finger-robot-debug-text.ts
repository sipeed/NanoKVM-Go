export function formatFingerRobotState(value: string, text: FingerRobotDebugText): string {
  switch (value.trim().toLowerCase()) {
    case '':
    case 'idle':
      return text.idle;
    case 'press':
    case 'pressed':
    case 'pressing':
      return text.pressing;
    case 'release':
    case 'released':
    case 'releasing':
      return text.releasing;
    case 'reset':
    case 'resetting':
    case 'zero':
      return text.resetting;
    default:
      return value;
  }
}

export function formatFingerRobotResult(value: string, text: FingerRobotDebugText): string {
  switch (value.trim().toLowerCase()) {
    case '':
    case 'idle':
      return text.idle;
    case 'running':
      return text.running;
    case 'complete':
    case 'completed':
    case 'success':
      return text.completed;
    case 'cancelled':
    case 'canceled':
    case 'shutdown':
    case 'stopped':
      return text.stopped;
    case 'reset_complete':
    case 'reset':
      return text.zeroed;
    case 'error':
    case 'failed':
      return text.failed;
    default:
      return value;
  }
}

export function getFingerRobotDebugText(language: string | undefined): FingerRobotDebugText {
  return fingerRobotDebugText[normalizeLanguage(language)];
}
