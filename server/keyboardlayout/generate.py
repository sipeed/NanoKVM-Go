"""Generate data.go from the Windows XML files in Unicode CLDR release-43/keyboards/windows.

Run with a local copy of that directory as the argument, then run gofmt on data.go.
Source: https://github.com/unicode-org/cldr/tree/release-43/keyboards/windows
"""
import itertools
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

profiles = {
    "en-US": "en", "en-GB": "en-GB", "fr-CA": "fr-CA:var",
    "ru-RU": "ru", "fa-IR": "fa", "fa-IR-standard": "fa:extended",
    "fr-CA-multilingual": "fr-CA", "fr-FR": "fr", "de-DE": "de", "es-ES": "es",
}
# ISO keyboard positions (CLDR) to USB HID Keyboard/Keypad usage IDs.
positions = {}
for row, first, codes in [
    ("E", 0, [53, *range(30, 40), 45, 46]),
    ("D", 1, [20, 26, 8, 21, 23, 28, 24, 12, 18, 19, 47, 48]),
    ("C", 1, [4, 22, 7, 9, 10, 11, 13, 14, 15, 51, 52, 49]),
    ("B", 0, [100, 29, 27, 6, 25, 5, 17, 16, 54, 55, 56]),
    ("A", 3, [44]),
]:
    for index, code in enumerate(codes, first):
        positions[f"{row}{index:02}"] = code

modifiers = {"": 0, "shift": 2, "shift+caps?": 2, "altR+caps?": 64, "altR+shift+caps?": 66}


def decode(value):
    return re.sub(r"\\u\{([a-fA-F0-9]+)\}", lambda m: chr(int(m[1], 16)), value)


def quote(value):
    return json.dumps(value, ensure_ascii=False).replace("\u00a0", "\\u00a0")


def generate(layout_id, root):
    transforms = {}
    for transform in root.findall(".//transform"):
        accent, base = decode(transform.attrib["from"])
        transforms.setdefault(accent, {})[base] = decode(transform.attrib["to"])

    direct = {}
    dead = {}
    for layer in root.findall("keyMap"):
        mod = modifiers.get(layer.get("modifiers", "").partition(" ")[0])
        if mod is None:
            continue
        for key in layer.findall("map"):
            char = decode(key.attrib["to"])
            # A one-key ligature that produces several characters cannot be inverted rune by rune.
            if len(char) != 1:
                continue
            stroke = (mod, positions[key.attrib["iso"]])
            table = dead if char in transforms and key.get("transform") != "no" else direct
            table.setdefault(char, stroke)

    lines = [f'// {root.find(".//name").attrib["value"]}', f'{quote(layout_id)}: {{', 'direct: []keyRun{']
    # Group consecutive usage IDs on the same modifier layer.
    for mod, layer in itertools.groupby(sorted((m, k, c) for c, (m, k) in direct.items()), lambda entry: entry[0]):
        for _, run in itertools.groupby(enumerate(layer), lambda v: v[1][1] - v[0]):
            keys = [entry for _, entry in run]
            lines.append(f'{{{mod}, {keys[0][1]}, {quote("".join(k[2] for k in keys))}}},')
    lines.append('},')
    if dead:
        lines.append('accents: []accentKey{')
        for accent, (mod, code) in dead.items():
            pairs = transforms[accent]
            lines.append(f'{{Stroke{{{mod}, {code}}}, {quote("".join(pairs))}, {quote("".join(pairs.values()))}}},')
        lines.append('},')
    lines.append('},')
    return lines


lines = ['// Code generated by generate.py from Unicode CLDR 43. See LICENSE-CLDR.', 'package keyboardlayout', '', 'var profiles = map[string]profile{']
for layout_id, source in profiles.items():
    lang, _, variant = source.partition(":")
    filename = lang + "-t-k0-windows" + ("-" + variant if variant else "") + ".xml"
    lines.extend(generate(layout_id, ET.parse(Path(sys.argv[1]) / filename)))
Path(__file__).with_name("data.go").write_text("\n".join(lines + ["}", ""]), encoding="utf-8")
